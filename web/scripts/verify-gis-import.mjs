section("GeoPackage");
{
  const gpkg = new Uint8Array(gunzipSync(readFileSync(fixture("zoning-3424.gpkg.gz"))));

  const layers = geoPackageLayers(gpkg);
  assert.deepEqual(
    layers.map((layer) => layer.name),
    ["zoning_districts", "big_overflow"]
  );
  assert.equal(layers[0].srsId, 3424);
  assert.equal(layers[0].geometryColumn, "geom");
  passed("lists both feature layers with their SRS and geometry column");

  assert.throws(() => readGeoPackage(gpkg), /holds 2 layers/);
  assert.throws(() => readGeoPackage(gpkg, "nope"), /no layer named/);
  passed("a multi-layer file requires the layer to be named");

  const districts = readGeoPackage(gpkg, "zoning_districts");
  assert.match(districts.crs.name, /New Jersey/);
  assertMatchesSource(districts, source, "geopackage");

  // A row of ~9.5 KB cannot fit on a 4 KB SQLite page, so this layer only reads
  // correctly if the overflow-page chain is followed.
  const overflow = readGeoPackage(gpkg, "big_overflow");
  const expected = jsonOf("big-overflow-source.geojson").features;
  assert.ok(expected[0].properties.LONGNOTE.length > 4096, "fixture must exceed one page");
  assertMatchesSource(overflow, expected, "geopackage overflow rows");
  assert.equal(
    overflow.features[0].properties.LONGNOTE.length,
    expected[0].properties.LONGNOTE.length,
    "the spilled text field is reassembled to its full length"
  );
  passed(`rows spilling onto overflow pages are reassembled (${expected[0].properties.LONGNOTE.length} bytes)`);
}

