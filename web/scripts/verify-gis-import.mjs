const source = jsonOf("zoning-source.geojson").features;

section("Zipped shapefile (EPSG:3424 → WGS84)");
{
  const result = await readShapefileZip(bytesOf("zoning-3424.shp.zip"));
  assert.equal(result.layerName, "zoning");
  assert.match(result.crs.name, /New_Jersey/);
  assert.deepEqual(result.warnings, []);
  assertMatchesSource(result, source, "shapefile");

  // The hole in district AA is the case a flat ring list gets wrong: read as
  // three separate polygons, the courtyard becomes buildable land.
  const aa = result.features.find((feature) => feature.properties.ZONE === "AA");
  assert.equal(aa.geometry.type, "Polygon");
  assert.equal(aa.geometry.coordinates.length, 2, "district AA keeps its interior ring");
  const aaa = result.features.find((feature) => feature.properties.ZONE === "AAA");
  assert.equal(aaa.geometry.type, "MultiPolygon");
  assert.equal(aaa.geometry.coordinates.length, 2, "district AAA keeps both of its parts");
  passed("interior rings stay holes and multi-part districts stay multi-part");
}

