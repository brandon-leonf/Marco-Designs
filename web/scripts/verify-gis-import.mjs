section("Zip reader");
{
  const entries = await readZip(bytesOf("zoning-3424.shp.zip"));
  const names = entries.map((entry) => entry.name).sort();
  assert.deepEqual(names, ["zoning.dbf", "zoning.prj", "zoning.shp", "zoning.shx"]);
  passed("lists a zipped shapefile's members");

  assert.ok(findZipEntry(entries, ".SHP"), "extension lookup is case-insensitive");
  assert.equal(findZipEntry(entries, ".gpkg"), null);
  const shp = await findZipEntry(entries, ".shp").read();
  assert.equal(shp.length, findZipEntry(entries, ".shp").size);
  assert.equal(new DataView(shp.buffer, shp.byteOffset).getInt32(0, false), 9994);
  passed("decompresses an entry to its declared length");

  await assert.rejects(readZip(new Uint8Array(200)), /not a zip archive/);
  passed("a non-archive is refused");
}

section("XML reader");
{
  const root = parseXml(
    '<?xml version="1.0"?><kml:Document xmlns:kml="x"><!-- skip me -->' +
      "<Placemark id='a'><name>R&amp;D &#65;rea</name>" +
      "<description><![CDATA[<b>3 > 2</b>]]></description><Point/></Placemark>" +
      "<Placemark><name>Second</name></Placemark></kml:Document>"
  );
  const placemarks = findAll(root, "Placemark");
  assert.equal(placemarks.length, 2);
  assert.equal(placemarks[0].attributes.id, "a");
  assert.equal(textOf(placemarks[0], "name"), "R&D Area");
  assert.equal(textOf(placemarks[0], "description"), "<b>3 > 2</b>");
  assert.equal(placemarks[0].children.some((child) => child.name === "Point"), true);
  passed("namespaces, entities, CDATA, comments and self-closing tags");

  assert.throws(() => parseXml("not xml at all"), /no XML elements/);
  passed("a non-XML document is refused");
}

