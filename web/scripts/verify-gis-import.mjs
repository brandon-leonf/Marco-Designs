// A zoning boundary is never surveyed to better than a metre, and the database
// stores it in feet. One centimetre — 1e-7 degrees — is therefore far tighter
// than the data warrants and still catches any real error in the maths.
const TOLERANCE_DEG = 1e-7;

// One degree of latitude is about 111.32 km, which is close enough for turning a
// tolerance into a distance a person can judge.
const DEG_TO_MM = 1.1132e8;
const DEG_TO_CM = 1.1132e7;

let checks = 0;
const passed = (label) => {
  checks += 1;
  console.log(`  ok  ${label}`);
};
const section = (label) => console.log(`\n${label}`);

/* ------------------------------------------------------------ geometry compare */

/**
 * A ring in a form that does not depend on where it starts or which way it
 * winds. Two readers can produce the same ring beginning at a different vertex
 * or in the opposite direction and both be right, so the comparison has to
 * ignore exactly those two freedoms and nothing else.
 */
function canonicalRing(ring) {
  const open = ring.slice(0, -1);
  const forward = ringSignedArea(ring) > 0 ? open : [...open].reverse();
  let best = 0;
  for (let index = 1; index < forward.length; index += 1) {
    const [x, y] = forward[index];
    const [bx, by] = forward[best];
    if (x < bx - 1e-12 || (Math.abs(x - bx) <= 1e-12 && y < by - 1e-12)) best = index;
  }
  return [...forward.slice(best), ...forward.slice(0, best)];
}

function canonicalPolygons(geometry) {
  const polygons =
    geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  return polygons
    .map((polygon) => polygon.map(canonicalRing))
    .sort((a, b) => a[0][0][0] - b[0][0][0] || a[0][0][1] - b[0][0][1]);
}

function assertSameGeometry(actual, expected, label) {
  assert.equal(actual.type, expected.type, `${label}: geometry type`);
  const got = canonicalPolygons(actual);
  const want = canonicalPolygons(expected);
  assert.equal(got.length, want.length, `${label}: polygon count`);

  let worst = 0;
  got.forEach((polygon, polygonIndex) => {
    assert.equal(polygon.length, want[polygonIndex].length, `${label}: ring count`);
    polygon.forEach((ring, ringIndex) => {
      const target = want[polygonIndex][ringIndex];
      assert.equal(ring.length, target.length, `${label}: vertex count`);
      ring.forEach(([x, y], vertex) => {
        worst = Math.max(worst, Math.abs(x - target[vertex][0]), Math.abs(y - target[vertex][1]));
      });
    });
  });
  assert.ok(
    worst <= TOLERANCE_DEG,
    `${label}: worst vertex offset ${worst.toExponential(3)}° exceeds ${TOLERANCE_DEG}°`
  );
  return worst;
}

/** RFC 7946 §3.1.6: exterior rings counter-clockwise, holes clockwise. */
function assertRfc7946Winding(geometry, label) {
  const polygons = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  polygons.forEach((polygon) => {
    polygon.forEach((ring, index) => {
      const counterClockwise = ringSignedArea(ring) > 0;
      assert.equal(
        counterClockwise,
        index === 0,
        `${label}: ring ${index} is wound the wrong way for RFC 7946`
      );
    });
  });
}

/**
 * Compare a reader's output with the ground-truth GeoJSON, matching features by
 * their zone code rather than by position — a container is free to reorder rows,
 * and only the pairing of attributes to geometry has to survive.
 */
function assertMatchesSource(result, expectedFeatures, label, { codeField = "ZONE" } = {}) {
  assert.equal(result.features.length, expectedFeatures.length, `${label}: feature count`);
  let worst = 0;

  for (const expected of expectedFeatures) {
    const code = expected.properties[codeField];
    const actual = result.features.find((feature) => feature.properties[codeField] === code);
    assert.ok(actual, `${label}: no feature carries ${codeField}=${code}`);

    for (const [key, value] of Object.entries(expected.properties)) {
      assert.equal(
        String(actual.properties[key] ?? ""),
        String(value ?? ""),
        `${label}: ${code} attribute ${key}`
      );
    }
    const normalized = toPolygonal(actual.geometry);
    assertRfc7946Winding(normalized, `${label}: ${code}`);
    worst = Math.max(worst, assertSameGeometry(normalized, expected.geometry, `${label}: ${code}`));
  }
  passed(`${label} — ${result.features.length} features, worst offset ${(worst * DEG_TO_CM).toFixed(2)} cm`);
}

/* ------------------------------------------------------------------ projection */

section("Projection inverses against gdaltransform control points");
{
  // Produced by: gdaltransform -s_srs EPSG:4269 -t_srs EPSG:<code>
  // NAD83 on both sides, so no datum shift is folded into the expected values.
  const cases = [
    {
      label: "EPSG:3424 NJ State Plane (US survey feet), from the fixture's own .prj",
      crs: null, // filled in below from the shapefile
      points: [
        [[593632.308826151, 804347.391770293], [-74.132, 41.041]],
        [[596934.403430431, 806183.162687174], [-74.12, 41.046]],
        [[295743.876322155, 389260.052188968], [-75.2, 39.9]],
        [[659715.116357887, 498332.787866255], [-73.9, 40.2]],
      ],
    },
    {
      label: "EPSG:2263 New York Long Island (Lambert Conformal Conic)",
      crs: resolveCrs({ epsg: 2263 }),
      points: [
        [[984250, 194305.338941152], [-74, 40.7]],
        [[1122265.7776222, 304000.756674009], [-73.5, 41]],
        [[1537099.93687913, 273483.915309214], [-72, 40.9]],
      ],
    },
    {
      label: "EPSG:3857 Web Mercator",
      crs: resolveCrs({ epsg: 3857 }),
      points: [[[-8252336.49148696, 5018391.03670106], [-74.132, 41.041]]],
    },
    {
      label: "Albers Equal Area (EPSG:5070 parameters)",
      crs: crsFromWkt(
        'PROJCS["NAD83 / Conus Albers",GEOGCS["NAD83",DATUM["North_American_Datum_1983",' +
          'SPHEROID["GRS 1980",6378137,298.257222101]],PRIMEM["Greenwich",0],' +
          'UNIT["degree",0.0174532925199433]],PROJECTION["Albers_Conic_Equal_Area"],' +
          'PARAMETER["standard_parallel_1",29.5],PARAMETER["standard_parallel_2",45.5],' +
          'PARAMETER["latitude_of_center",23],PARAMETER["longitude_of_center",-96],' +
          'PARAMETER["false_easting",0],PARAMETER["false_northing",0],UNIT["metre",1]]'
      ),
      points: [
        [[0, 1886977.5648988], [-96, 40]],
        [[-314879.723162207, 2452348.40949526], [-100, 45]],
      ],
    },
  ];

  const prjEntries = await readZip(bytesOf("zoning-3424.shp.zip"));
  const prjText = new TextDecoder().decode(await findZipEntry(prjEntries, ".prj").read());
  cases[0].crs = crsFromWkt(prjText);
  assert.equal(cases[0].crs.method, "Transverse_Mercator");
  assert.match(cases[0].crs.unit, /US survey foot/i);

  for (const { label, crs, points } of cases) {
    let worst = 0;
    for (const [[x, y], [lon, lat]] of points) {
      const [gotLon, gotLat] = crs.inverse(x, y);
      worst = Math.max(worst, Math.abs(gotLon - lon), Math.abs(gotLat - lat));
    }
    assert.ok(
      worst < 1e-8,
      `${label}: worst offset ${worst.toExponential(3)}° is more than 1e-8°`
    );
    passed(`${label} — within ${(worst * DEG_TO_MM).toFixed(3)} mm of GDAL`);
  }

  // An unknown EPSG code has to be refused: reading State Plane feet as degrees
  // would put the layer in the Gulf of Guinea, and a warning is not enough.
  assert.throws(() => resolveCrs({ epsg: 26986 }), /does not know how to convert/);
  passed("an unrecognised EPSG code is refused rather than assumed");

  const undeclared = resolveCrs({});
  assert.equal(undeclared.isGeographic, true);
  assert.match(undeclared.warnings[0], /declares no coordinate reference system/);
  passed("a source with no CRS is read as longitude/latitude, with a warning");

  const nad27 = crsFromWkt(
    'PROJCS["NAD27 / NJ",GEOGCS["NAD27",DATUM["North_American_Datum_1927",' +
      'SPHEROID["Clarke 1866",6378206.4,294.9786982]],PRIMEM["Greenwich",0],' +
      'UNIT["degree",0.0174532925199433]],PROJECTION["Transverse_Mercator"],' +
      'PARAMETER["latitude_of_origin",38.8333333333],PARAMETER["central_meridian",-74.5],' +
      'PARAMETER["scale_factor",0.9999],PARAMETER["false_easting",2000000],' +
      'PARAMETER["false_northing",0],UNIT["US survey foot",0.304800609601219]]'
  );
  assert.match(nad27.warnings.join(" "), /NAD27/);
  passed("a NAD27 layer loads with the datum offset called out");
}

