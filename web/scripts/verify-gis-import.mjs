// Verifies the zoning-layer importer against fixtures produced by GDAL.
//
//   npm run test:gis
//
// The point of this script is that the file readers in src/lib/gis are written
// from the format specifications rather than taken from a library, so they need
// something authoritative to be checked against. Every fixture in
// scripts/fixtures was written by `ogr2ogr` from one committed GeoJSON file:
//
//   zoning-source.geojson        the truth, NAD83 longitude/latitude
//   zoning-3424.shp.zip          the same three districts as a zipped shapefile
//                                projected to NJ State Plane feet
//   zoning.kml / zoning.kmz      the same, as KML and as a KMZ archive
//   zoning-3424.gpkg.gz          the same as a GeoPackage, plus a second layer
//                                whose rows are large enough to spill onto
//                                SQLite overflow pages
//   big-overflow-source.geojson  the truth for that second layer
//
// So each reader has to reproduce a known answer through a different container,
// a different attribute encoding and — for the shapefile and GeoPackage — a
// reprojection out of State Plane feet. The projection maths is additionally
// checked against control points computed by `gdaltransform`, which is the only
// part of this whose correctness is not visible in the output.
//
// The fixtures are regenerated by scripts/build-gis-fixtures.sh, which needs
// GDAL. This script needs only Node, so CI can run it.

