section("ArcGIS JSON geometry");
{
  // Clockwise outer ring, counter-clockwise hole, then a second outer ring —
  // the shape of every real zoning polygon with an exclusion in it.
  const converted = esriGeometryToGeoJson({
    rings: [
      [[-74.132, 41.041], [-74.132, 41.046], [-74.126, 41.046], [-74.126, 41.041], [-74.132, 41.041]],
      [[-74.13, 41.042], [-74.128, 41.042], [-74.128, 41.044], [-74.13, 41.044], [-74.13, 41.042]],
      [[-74.12, 41.041], [-74.12, 41.046], [-74.114, 41.046], [-74.114, 41.041], [-74.12, 41.041]],
    ],
  });
  assert.equal(converted.type, "MultiPolygon");
  assert.equal(converted.coordinates.length, 2, "two outer rings make two polygons");
  assert.equal(converted.coordinates[0].length, 2, "the hole stays with its own polygon");
  assert.equal(converted.coordinates[1].length, 1);
  assertRfc7946Winding(converted, "esri rings");
  passed("a flat ring list becomes polygons with their holes attached");

  assert.equal(esriGeometryToGeoJson({ rings: [] }), null);
  assert.equal(esriGeometryToGeoJson(null), null);
  assert.equal(esriGeometryToGeoJson({ x: -74, y: 41 }).type, "Point");
  passed("empty and non-polygon geometries are handled without throwing");
}

