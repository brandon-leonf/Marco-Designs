section("Identifying the district-code field");
{
  const features = [
    {
      properties: {
        OBJECTID: 1,
        ZONE: "R-1",
        ZONENAME: "One Family Residential",
        Shape_Area: 12345.678,
        ORDINANCE: "223-35",
        GlobalID: "{a}",
      },
    },
    {
      properties: {
        OBJECTID: 2,
        ZONE: "R-1",
        ZONENAME: "One Family Residential",
        Shape_Area: 4321.1,
        ORDINANCE: "223-35",
        GlobalID: "{b}",
      },
    },
    {
      properties: {
        OBJECTID: 3,
        ZONE: "C-2",
        ZONENAME: "Neighbourhood Commercial",
        Shape_Area: 999.9,
        ORDINANCE: "223-40",
        GlobalID: "{c}",
      },
    },
  ];

  const ranked = rankCodeFields(features);
  assert.equal(ranked[0].name, "ZONE", `expected ZONE first, got ${ranked.map((r) => r.name)}`);
  assert.equal(
    ranked.some((candidate) => /objectid|shape_area|globalid/i.test(candidate.name)),
    false,
    "identity and geometry fields are excluded outright"
  );
  passed(`ZONE identified as the code field (candidates: ${ranked.map((r) => r.name).join(", ")})`);

  const names = rankCodeFields(features, { namesInstead: true });
  assert.equal(names[0].name, "ZONENAME");
  passed("ZONENAME identified as the district-name field");

  // A layer with no obviously named field still has to produce a ranking, but a
  // per-feature unique value must not win it.
  const awkward = rankCodeFields([
    { properties: { SYMBOL: "AA", ID: "row-1" } },
    { properties: { SYMBOL: "AA", ID: "row-2" } },
    { properties: { SYMBOL: "ML-7", ID: "row-3" } },
    { properties: { SYMBOL: "ML-7", ID: "row-4" } },
    { properties: { SYMBOL: "AAA", ID: "row-5" } },
    { properties: { SYMBOL: "AAA", ID: "row-6" } },
  ]);
  assert.equal(awkward[0].name, "SYMBOL");
  passed("a repeated short code outranks a value that is unique per feature");

  const values = distinctValues(features, "ZONE");
  assert.deepEqual(values, [
    { value: "C-2", count: 1 },
    { value: "R-1", count: 2 },
  ]);
  passed("distinct codes are counted and sorted for the mapping table");
}

section("Matching source codes onto configured districts");
{
  assert.equal(looseCodeKey(" r-1 "), "R1");
  assert.equal(looseCodeKey("ML 7"), "ML7");
  assert.notEqual(looseCodeKey("R1"), looseCodeKey("R1A"));
  passed("case, spacing and separators are ignored; the code itself is not");

  const districts = [{ code: "AA" }, { code: "ML-7" }, { code: "AAA" }];
  const matched = matchDistrictCodes(["AA", "ML 7", "aaa", "B"], districts);
  assert.deepEqual(matched.mapping, { AA: "AA", "ML 7": "ML-7", aaa: "AAA", B: "" });
  assert.deepEqual(matched.unmatched, ["B"]);
  // Only "ML 7" is a loose match. "aaa" differs from "AAA" by case alone, which
  // is an exact match — a district code is not case-sensitive anywhere else in
  // the application either, and the publish RPC compares them with upper().
  assert.deepEqual(
    matched.looseMatches.map((entry) => entry.sourceCode),
    ["ML 7"]
  );
  passed("exact matches, loose matches and genuine gaps are separated");

  // A town with both R-1 and R1 configured: guessing which one "R 1" means
  // would assign polygons to the wrong district's rules.
  const ambiguous = matchDistrictCodes(["R 1"], [{ code: "R-1" }, { code: "R1" }]);
  assert.equal(ambiguous.mapping["R 1"], "");
  assert.deepEqual(ambiguous.unmatched, ["R 1"]);
  passed("an ambiguous loose match is left for the operator to resolve");

  const gaps = missingDistricts(
    [
      { properties: { ZONE: "AA", ZONENAME: "One Family Residential" } },
      { properties: { ZONE: "B", ZONENAME: "Business" } },
      { properties: { ZONE: "B", ZONENAME: "Business" } },
    ],
    "ZONE",
    "ZONENAME",
    [{ code: "AA" }]
  );
  assert.deepEqual(gaps, [{ code: "B", name: "Business" }]);
  passed("districts absent from the config are reported with names from the layer");
}

